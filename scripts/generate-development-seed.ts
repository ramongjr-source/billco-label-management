import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { migrateDatabase, openProductDatabase } from '../database/index.js'
import { inspectProductWorkbook, previewProductImport } from '../server/import/index.js'

/** Use the production validation/mapping rules; never infer missing label data. */
export async function generateDevelopmentSeed(buffer: Buffer) {
  const db = openProductDatabase(':memory:')
  try {
    migrateDatabase(db)
    const inspection = await inspectProductWorkbook(buffer, 'BillcoMaster')
    const preview = await previewProductImport(db, buffer, 'BillcoMaster', inspection.mapping)
    if (!preview.rows.length) throw new Error('BillcoMaster contains no valid products; seed was not replaced.')
    return {
      sourceSha256: createHash('sha256').update(buffer).digest('hex'),
      sheetName: preview.sheetName,
      totalRows: preview.totalRows,
      blankRows: preview.blankRows,
      invalidRows: preview.invalidRows,
      errors: preview.errors,
      products: preview.rows.map(({ product }) => product),
    }
  } finally {
    db.close()
  }
}

async function main() {
  const [filename, output = 'database/seeds/billco-master.ts'] = process.argv.slice(2)
  if (!filename) throw new Error('Usage: npm run db:seed:generate -- <Billco_App_Master.xlsx> [output.ts]')
  const { products, ...source } = await generateDevelopmentSeed(readFileSync(resolve(filename)))
  const content = '// Generated by npm run db:seed:generate. Do not edit by hand.\n'
    + "import type { Product } from '../../shared/product.js'\n\n"
    + `export const billcoMasterSource = ${JSON.stringify(source, null, 2)} as const\n\n`
    + 'export const billcoMasterProducts: Product[] = [\n'
    + products.map((product) => `  ${JSON.stringify(product)},`).join('\n') + '\n]\n'
  writeFileSync(resolve(output), content)
  console.info(`Generated ${products.length} BillcoMaster products; skipped ${source.blankRows} blank and ${source.invalidRows} invalid rows.`)
  for (const error of source.errors) console.warn(`Row ${error.row}: ${error.field}: ${error.message}`)
}

